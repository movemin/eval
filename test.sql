-- 기존 테이블이 있다면 삭제 (초기화용)
DROP TABLE EMP CASCADE CONSTRAINTS;
DROP TABLE DEPT CASCADE CONSTRAINTS;
DROP TABLE SALGRADE CASCADE CONSTRAINTS;
DROP TABLE BONUS CASCADE CONSTRAINTS;

-- 1. DEPT (부서 테이블) 생성
CREATE TABLE DEPT (
    DEPTNO NUMBER(2) CONSTRAINT PK_DEPT PRIMARY KEY,
    DNAME  VARCHAR2(14),
    LOC    VARCHAR2(13)
);

-- 2. EMP (사원 테이블) 생성
CREATE TABLE EMP (
    EMPNO    NUMBER(4) CONSTRAINT PK_EMP PRIMARY KEY,
    ENAME    VARCHAR2(10),
    JOB      VARCHAR2(9),
    MGR      NUMBER(4),
    HIREDATE DATE,
    SAL      NUMBER(7,2),
    COMM     NUMBER(7,2),
    DEPTNO   NUMBER(2) CONSTRAINT FK_DEPTNO REFERENCES DEPT
);

-- 3. SALGRADE (급여 등급 테이블) 생성
CREATE TABLE SALGRADE (
    GRADE NUMBER,
    LOSAL NUMBER,
    HISAL NUMBER
);

-- 4. BONUS (보너스 테이블) 생성
CREATE TABLE BONUS (
    ENAME VARCHAR2(10),
    JOB   VARCHAR2(9),
    SAL   NUMBER,
    COMM  NUMBER
);

