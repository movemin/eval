# [실무] 집합(set) — 생성 + CRUD
#
# set: "중복 없는" 값들의 묶음. 순서가 없고, 인덱스로 접근할 수 없다.
#      대신 "이 값이 들어 있나?"를 확인하는 멤버십 검사가 매우 빠르고(O(1)),
#      합집합·교집합 같은 집합 연산을 바로 쓸 수 있다.
#      (예: 중복 제거, 방문 여부 체크, 권한/태그 비교, 두 목록의 공통/차이 …)
#
# CRUD: set은 "원소 추가/삭제"가 중심이다.
#       개별 원소를 직접 수정하는 개념은 없어서, 필요하면 빼고 다시 넣는다.

# ============================================================
# 0. 생성 (초기화)
# ============================================================
empty = set()                       # 빈 집합은 반드시 set()으로 만든다. {}는 빈 dict다.
nums = {3, 1, 2, 2, 3}              # 리터럴 (중복은 자동 제거 → {1, 2, 3})
from_list = set([1, 1, 2, 3, 3])   # 리스트의 중복 제거 → {1, 2, 3}
chars = set("banana")              # 문자열 → {'b', 'a', 'n'}
comp = {n for n in range(10) if n % 2 == 0}   # 집합 컴프리헨션 → {0,2,4,6,8}

print("생성:", nums, from_list, chars, comp)

# 가장 흔한 활용: 리스트 중복 제거
emails = ["a@x.com", "b@x.com", "a@x.com"]
unique = list(set(emails))         # 중복 제거 후 다시 리스트로 변환 (순서는 보장되지 않음)
print("중복 제거:", unique)


# ============================================================
# 1. Create — 추가
# ============================================================
tags = {"python", "backend"}
tags.add("api")                    # 원소 하나 추가
tags.add("python")                 # 이미 있으면 무시된다. set은 중복을 허용하지 않는다.
tags.update(["db", "docker"])      # 여러 개 한 번에 추가
print("\nCreate:", tags)


# ============================================================
# 2. Read — 읽기 / 조회
# ============================================================
print("\n[Read]")
print("api 포함?:", "api" in tags)      # 멤버십 검사 — set의 핵심 강점(빠름)
print("개수    :", len(tags))
# print(tags[0])                        # ✗ TypeError: set은 인덱싱 불가(순서 없음)
for t in tags:                          # 순회는 가능 (단, 순서는 보장되지 않음)
    print("  -", t)


# ============================================================
# 3. Update — 집합 연산으로 갱신
# ============================================================
a = {"읽기", "쓰기", "삭제"}            # 사용자가 가진 권한
b = {"읽기", "쓰기", "관리자"}          # 어떤 작업에 필요한 권한

print("\n[집합 연산]")
print("합집합(|)   :", a | b)          # 둘 중 하나라도 있는 것
print("교집합(&)   :", a & b)          # 둘 다 있는 것 (공통 권한)
print("차집합(-)   :", a - b)          # a에만 있는 것
print("대칭차(^)   :", a ^ b)          # 한쪽에만 있는 것

a |= {"승인"}                          # |=, &=, -= 로 자기 자신을 바로 갱신할 수 있다.
print("승인 추가:", a)

# 예: 두 명단을 비교해 새로 들어온 사람과 빠진 사람 찾기
yesterday = {"민수", "서연", "지우"}
today = {"서연", "지우", "현우"}
print("새로 온 사람:", today - yesterday)   # {'현우'}
print("빠진 사람  :", yesterday - today)    # {'민수'}


# ============================================================
# 4. Delete — 삭제
# ============================================================
print("\n[Delete]")
tags.discard("docker")             # 삭제 (없어도 에러가 나지 않아 안전)
tags.discard("없는태그")            # 없어도 조용히 넘어간다.
tags.remove("db")                  # 삭제 (없으면 KeyError)
popped = tags.pop()                # 임의의 원소 하나를 꺼내며 삭제 (순서 없음)
print("남은 태그:", tags, "| pop:", popped)

tags.clear()                       # 전체 비우기
print("clear 후:", tags)


# ============================================================
# 5. 실무 팁
# ============================================================
# - "중복 제거"가 필요하면 1순위로 set을 떠올린다.
# - "포함 여부"를 자주 확인하는 데이터는 list보다 set이 훨씬 빠르다(ex03 참고).
# - 두 데이터의 공통/추가/삭제 항목 비교는 & - ^ 연산으로 한 줄에 끝난다.
# - 삭제할 때는 remove(없으면 에러)보다 discard(없어도 안전)가 더 방어적이다.
# - set은 순서·인덱스가 없다 → 순서가 중요하면 list를 써야 한다.
