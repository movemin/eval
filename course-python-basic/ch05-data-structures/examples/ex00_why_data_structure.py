# 왜 자료구조가 필요한가?
#
# 변수 하나에는 보통 값 하나를 담는다.
# 학생 30명의 점수, 도시 100곳의 기온처럼
# 서로 관련된 값을 한꺼번에 다루려면 자료구조가 필요하다.

# --- 변수만 사용 (한계) ---
score1 = 85
score2 = 92
score3 = 78
score4 = 88
# ...
score30 = 95

# 평균을 구하려면 변수를 하나씩 직접 더해야 한다.
avg = (score1 + score2 + score3 + score4 + score30) / 5
print("변수만 사용:", avg)

print()

# --- 리스트(자료구조) 사용 ---
scores = [85, 92, 78, 88,
          90, 76, 100, 82,
          # ... 30개의 점수
          95]

# 리스트에 모아 두면 한 줄로 평균을 구할 수 있다.
avg = sum(scores) / len(scores)
print("리스트 사용:", avg)
