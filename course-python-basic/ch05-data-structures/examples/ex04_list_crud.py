# [실무] 리스트(list) — 생성 + CRUD
#
# list: 순서가 있고, 중복을 허용하며, 언제든 수정 가능한 자료구조.
#       여러 값을 순서대로 모아 두고 자주 추가/삭제할 때 기본으로 선택한다.
#       (예: 장바구니, 로그, 대기열, 조회 결과 목록 …)
#
# CRUD = Create(추가) / Read(읽기) / Update(수정) / Delete(삭제)

# ============================================================
# 0. 생성 (초기화) — 자주 쓰는 방법들
# ============================================================
empty1 = []                       # 빈 리스트 (가장 흔함)
empty2 = list()                   # 함수로도 만들 수 있다.

nums = [3, 1, 2]                  # 값으로 바로 초기화
chars = list("abc")              # 문자열 → ['a', 'b', 'c']
seq = list(range(1, 6))          # range → [1, 2, 3, 4, 5]
zeros = [0] * 5                  # 같은 값 반복 → [0, 0, 0, 0, 0]

# 리스트 컴프리헨션: 다른 데이터를 바탕으로 새 리스트 만들기
squares = [n * n for n in range(1, 6)]        # [1, 4, 9, 16, 25]
evens = [n for n in range(10) if n % 2 == 0]  # 조건 필터 → [0, 2, 4, 6, 8]

print("생성:", empty1, nums, chars, seq, zeros)
print("컴프리헨션:", squares, evens)


# ============================================================
# 1. Create — 추가
# ============================================================
cart = ["사과", "바나나"]
cart.append("우유")              # 맨 뒤에 하나 추가 (가장 흔하고 빠름)
cart.insert(0, "빵")            # 특정 위치(0번)에 삽입. 앞쪽 삽입은 뒤 원소를 밀어 느릴 수 있다.
cart.extend(["계란", "치즈"])    # 여러 개를 한 번에 이어 붙이기
# 주의: cart.append(["계란","치즈"])처럼 쓰면 리스트 전체가 원소 하나로 들어간다.
print("\nCreate:", cart)


# ============================================================
# 2. Read — 읽기 / 조회
# ============================================================
print("\n[Read]")
print("첫 번째 :", cart[0])        # 인덱스로 접근
print("마지막  :", cart[-1])       # 음수 인덱스 = 뒤에서부터
print("앞 3개  :", cart[:3])       # 슬라이싱 → 새 리스트(복사본) 반환
print("개수    :", len(cart))
print("우유 포함?:", "우유" in cart)        # 멤버십 검사
print("우유 위치:", cart.index("우유"))     # 처음 나오는 위치
print("바나나 수:", cart.count("바나나"))   # 개수 세기
for i, item in enumerate(cart, 1):          # enumerate를 쓰면 번호와 값을 함께 꺼낼 수 있다.
    print(f"  {i}. {item}")


# ============================================================
# 3. Update — 수정
# ============================================================
cart[0] = "통밀빵"                # 인덱스로 값 교체
cart[1:3] = ["딸기", "포도"]      # 슬라이스 통째 교체
print("\nUpdate:", cart)

prices = [1000, 2000, 3000]
prices = [p * 1.1 for p in prices]   # 전체 변환(부가세 10%) 후 다시 저장
print("가격 갱신:", prices)


# ============================================================
# 4. Delete — 삭제
# ============================================================
cart.remove("우유")              # "값"으로 삭제 (첫 번째 하나만, 없으면 ValueError)
last = cart.pop()                # 맨 뒤 꺼내며 삭제 (꺼낸 값 반환)
first = cart.pop(0)              # 인덱스 지정도 가능 (앞쪽 pop은 느림)
del cart[0]                      # del 문으로 인덱스 삭제
print("\nDelete:", cart, "| 꺼낸 값:", first, last)

# 없는 값을 삭제하려 하면 에러가 나므로, 필요하면 먼저 확인한다.
target = "라면"
if target in cart:
    cart.remove(target)
else:
    print(f"'{target}'(은)는 목록에 없습니다.")

cart.clear()                     # 전체 비우기
print("clear 후:", cart)


# ============================================================
# 5. 실무 팁
# ============================================================
# - 추가/삭제는 맨 뒤에서 하는 append/pop이 빠르다. 맨 앞 삽입/삭제가 잦으면
#   collections.deque를 고려한다. (양쪽 끝에서 O(1))
# - 슬라이싱(list[a:b])은 항상 복사본을 만든다 → 원본 보호에 유용.
# - 변환·필터는 리스트 컴프리헨션으로 쓰면 짧고 읽기 쉽다.
# - 정렬: sorted(list)는 새 리스트 반환, list.sort()는 원본을 직접 정렬.
